def addNumbers(num1, num2):
    sum = num1 + num2
    print(sum)
    return
addNumbers(2,3)
addNumbers(4,5)

def subtractNumbers(num1, num2):
    sub = num1 - num2
    print(sub)
    return
subtractNumbers(10,5)

def multiplyNumbers(num1, num2):
    mul = num1 * num2
    print(mul)
    return
multiplyNumbers(3,4)

