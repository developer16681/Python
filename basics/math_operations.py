import math
print("1:", math.sqrt(16))             #1
print("2:", math.factorial(5))         #2
print("3:", math.gcd(12, 18))          #3
print("4:", math.sin(math.pi/2))       #4
print("5:", math.cos(0))                #5
print("6:", math.log(100, 10))         #6
print("7:", math.exp(2))                #7
print("8:", math.ceil(4.2))             #8
print("9:", math.floor(4.8))            #9
print("10:", math.radians(180))         #10
print("11:", math.degrees(math.pi))     #11
print("12:", math.isqrt(25))            #12
print("13:", math.pow(2, 3))           #13
print("14:", math.fabs(-5.5))           #14
print("15:", math.fmod(10, 3))          #15
print("16:", math.hypot(3, 4))          #16
print("17:", math.isclose(0.1 + 0.2, 0.3))  #17
print("18:", math.lcm(12, 18))          #18
print("19:", math.prod([1, 2, 3, 4]))     #19
print("20:", math.remainder(10, 3))        #20
print("21:", math.cos(90))                #21
print("22:", math.sin(0))                 #22